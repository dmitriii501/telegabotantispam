def seller() -> dict[str, str]:
    return {key: os.getenv(key, "").strip() for key in [*SELLER_FIELDS, "SUPPORT_CONTACT"]}


def missing_details() -> list[str]:
    s = seller()
    return [key for key in SELLER_FIELDS if not s[key]]


def val(key: str) -> str:
    """A value of the seller for the page; an empty one stays visibly empty so it is not published by accident."""
    value = seller().get(key, "")
    return html.escape(value) if value else f"<mark>[заполните {key} в .env]</mark>"


def n(value: int) -> str:
    return f"{value:,}".replace(",", " ")


def months_word(m: int) -> str:
    return {1: "1 месяц", 3: "3 месяца", 12: "12 месяцев"}.get(m, f"{m} мес.")


